import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import { act } from '@testing-library/react'
import App from '../src/App'

describe('PatternLab learning interface', () => {
  it('loads the default walkthrough and advances through real steps', () => {
    render(<App />)
    expect(screen.getByRole('heading', { name: 'Maximum Sum Subarray' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Next step' }))
    expect(screen.getByText(/STEP 02/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Go to step 9' }))
    expect(screen.getByText('Sum 9')).toBeInTheDocument()
  })
  it('validates new input and lets the learner switch examples', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('Array input'), { target: { value: '1, 2' } })
    fireEvent.change(screen.getByLabelText('Window K'), { target: { value: '1' } })
    fireEvent.click(screen.getByRole('button', { name: /Run trace/ }))
    expect(screen.getByRole('button', { name: 'Go to step 1' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Window K'), { target: { value: '99' } })
    fireEvent.click(screen.getByRole('button', { name: /Run trace/ }))
    expect(screen.getByRole('alert')).toHaveTextContent('K must be between')
    fireEvent.change(screen.getByRole('combobox', { name: 'Select algorithm example' }), { target: { value: 'longest-substring' } })
    expect(screen.getByLabelText('String input')).toHaveValue('abcabcbb')
  })
  it('supports play pause, reset, and selecting a timeline step', () => {
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: 'Next step' }))
    fireEvent.click(screen.getByRole('button', { name: 'Reset playback' }))
    expect(screen.getByText(/STEP 01/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Go to step 3' }))
    expect(screen.getByText(/STEP 03/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Previous step' }))
    expect(screen.getByText(/STEP 02/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Next step' }))
    fireEvent.click(screen.getByRole('button', { name: 'Play' }))
    expect(screen.getByRole('button', { name: 'Pause' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Pause' }))
  })
  it('supports keyboard step navigation and future-pattern placeholders', () => {
    render(<App />)
    fireEvent.keyDown(window, { key: 'ArrowRight' })
    expect(screen.getByText(/STEP 02/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /Two Pointers/ }))
    expect(screen.getByRole('heading', { name: 'Two Pointers ✳' })).toBeInTheDocument()
    expect(screen.getAllByText(/Indices \[1, 2\] · values \[2, 7\]/)).toHaveLength(2)
    fireEvent.click(screen.getByRole('button', { name: 'Explanation' }))
    expect(screen.getByText('Opposite directions')).toBeInTheDocument()
    expect(screen.queryByRole('combobox', { name: 'Select two pointers example' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /Problems/ }))
    expect(screen.getByRole('link', { name: 'Open 3Sum on LeetCode' })).toHaveAttribute('href', 'https://leetcode.com/problems/3sum/')
    expect(screen.queryByRole('combobox', { name: 'Select two pointers example' })).not.toBeInTheDocument()
    fireEvent.click(screen.getAllByRole('button', { name: 'Visualizer' })[0]!)
    fireEvent.change(screen.getByRole('combobox', { name: 'Select two pointers example' }), { target: { value: 'palindrome' } })
    expect(screen.getAllByText('true')).toHaveLength(2)
    fireEvent.click(screen.getByRole('button', { name: 'Next step' }))
    expect(screen.getByText(/STEP 02/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Sliding Window' }))
    expect(screen.getByRole('heading', { name: 'Maximum Sum Subarray' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'About PatternLab' }))
    expect(screen.getByText(/Learn patterns/)).toBeInTheDocument()
  })
  it('validates custom Two Pointers input and preserves a valid trace', () => {
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: /Two Pointers/ }))
    fireEvent.change(screen.getByLabelText('Array input'), { target: { value: '3, 1' } })
    fireEvent.click(screen.getByRole('button', { name: /Run trace/ }))
    expect(screen.getByRole('alert')).toHaveTextContent('sorted')
    expect(screen.getAllByText(/Indices \[1, 2\] · values \[2, 7\]/)).toHaveLength(2)
  })
  it('plays, pauses, resets, reaches the final step, and synchronizes Java lines', () => {
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: /Two Pointers/ }))
    expect(document.querySelector('.code-active')).toHaveTextContent('int left = 0')
    fireEvent.click(screen.getByRole('button', { name: 'Next step' }))
    expect(document.querySelector('.code-active')).toHaveTextContent('right--;')
    fireEvent.click(screen.getByRole('button', { name: 'Play' }))
    expect(screen.getByRole('button', { name: 'Pause' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Pause' }))
    fireEvent.click(screen.getByRole('button', { name: 'Reset playback' }))
    expect(screen.getByText(/STEP 01/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Go to step 3' }))
    expect(screen.getByText('FINAL RESULT')).toBeInTheDocument()
    expect(screen.getAllByText(/Indices \[1, 2\] · values \[2, 7\]/)).toHaveLength(2)
  })
  it('keeps Fast & Slow Pointers examples, explanation, and problem catalog in separate tabs', () => {
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: /Fast & Slow Pointers/ }))
    expect(screen.getByRole('heading', { name: 'Fast & Slow Pointers ✳' })).toBeInTheDocument()
    expect(screen.getAllByText('true').length).toBeGreaterThan(0)
    expect(screen.getByText(/Tail node #3 reconnects to node #1/)).toBeInTheDocument()
    expect(document.querySelector('.code-active')).toHaveTextContent('ListNode slow = head')
    fireEvent.click(screen.getByRole('button', { name: 'Next step' }))
    expect(document.querySelector('.code-active')).toHaveTextContent('slow = slow.next;')
    fireEvent.click(screen.getByRole('button', { name: 'Play' }))
    expect(screen.getByRole('button', { name: 'Pause' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Pause' }))
    fireEvent.click(screen.getByRole('button', { name: 'Reset playback' }))
    fireEvent.click(screen.getByRole('button', { name: 'Explanation' }))
    expect(screen.getByText('Detect a cycle')).toBeInTheDocument()
    expect(screen.queryByRole('combobox', { name: 'Select fast and slow example' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /Problems/ }))
    expect(screen.getByRole('link', { name: 'Open Happy Number on LeetCode' })).toHaveAttribute('href', 'https://leetcode.com/problems/happy-number/')
    expect(screen.getAllByText('Practice link')).toHaveLength(3)
    expect(screen.queryByRole('combobox', { name: 'Select fast and slow example' })).not.toBeInTheDocument()
    fireEvent.click(screen.getAllByRole('button', { name: 'Visualizer' })[0]!)
    fireEvent.change(screen.getByRole('combobox', { name: 'Select fast and slow example' }), { target: { value: 'middle' } })
    expect(screen.getAllByText('Node value 3')).toHaveLength(2)
    fireEvent.change(screen.getByRole('combobox', { name: 'Select fast and slow example' }), { target: { value: 'cycle' } })
    fireEvent.click(screen.getByRole('button', { name: 'Load no-cycle' }))
    expect(screen.getAllByText('false')).toHaveLength(2)
    fireEvent.change(screen.getByRole('combobox', { name: 'Select fast and slow example' }), { target: { value: 'happy' } })
    fireEvent.click(screen.getByRole('button', { name: 'Load unhappy (2)' }))
    expect(screen.getAllByText('false')).toHaveLength(2)
  })
  it('validates Pattern 03 inputs without replacing the last valid result', () => {
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: /Fast & Slow Pointers/ }))
    fireEvent.change(screen.getByLabelText('Cycle destination'), { target: { value: '12' } })
    fireEvent.click(screen.getByRole('button', { name: /Run trace/ }))
    expect(screen.getByRole('alert')).toHaveTextContent('Cycle destination')
    expect(screen.getAllByText('true').length).toBeGreaterThan(0)
  })
  it('does not let an old playback timer advance a newly generated trace', async () => {
    vi.useFakeTimers()
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: 'Play' }))
    fireEvent.change(screen.getByLabelText('Array input'), { target: { value: '1, 2, 3' } })
    fireEvent.change(screen.getByLabelText('Window K'), { target: { value: '2' } })
    fireEvent.click(screen.getByRole('button', { name: /Run trace/ }))
    expect(screen.getByText('1 / 6')).toBeInTheDocument()
    await act(async () => { vi.advanceTimersByTime(2200) })
    expect(screen.getByText('1 / 6')).toBeInTheDocument()
    vi.useRealTimers()
  })
})
